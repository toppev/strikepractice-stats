/** 1.8 numeric item id -> Bukkit Material name */
export function legacyNameFromNumber(id: number): string | undefined {
  if (id >= 0 && id < NUMERIC_IDS.length) return NUMERIC_IDS[id];
  if (id >= 256 && id < 256 + NUMERIC_ITEM_IDS.length) return NUMERIC_ITEM_IDS[id - 256];
  if (id >= 2256 && id <= 2267) return id === 2256 ? "GOLD_RECORD" : id === 2257 ? "GREEN_RECORD" : `RECORD_${id - 2255}`;
  return undefined;
}

/** Bukkit Material name (+ data value) -> modern item id, e.g. ("WOOL", 14) -> "red_wool" */
export function modernIdFromLegacy(name: string, data = 0): string {
  const upper = name.toUpperCase().replace(/^MINECRAFT:/, "");
  const byData = BY_DATA[upper];
  if (byData) return byData(data);
  return RENAMED[upper] ?? upper.toLowerCase();
}

