/** "DAMAGE_ALL", "Enchantment[16, DAMAGE_ALL]", "minecraft:sharpness", "SHARPNESS" -> "sharpness" */
export function enchantmentKey(raw: string): string {
  const bracket = /\[\s*\d+\s*,\s*([A-Z_]+)\s*\]/.exec(raw);
  const name = (bracket ? bracket[1] : raw).replace(/^minecraft:/, "");
  return ENCHANTMENTS[name.toUpperCase()] ?? name.toLowerCase();
}
